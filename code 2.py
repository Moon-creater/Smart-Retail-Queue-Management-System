import cv2, base64
from collections import deque
from IPython.display import HTML, display

MAX_FRAMES = 300
SMOOTH = 15
EDGES = [0.0, 0.25, 0.5, 0.75, 1.0]
TITLE = "SMART BILLING MONITOR"

cap = cv2.VideoCapture(video_path)
fps = cap.get(cv2.CAP_PROP_FPS) or 25
w = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
h = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
out = cv2.VideoWriter("raw.mp4", cv2.VideoWriter_fourcc(*"mp4v"), fps, (w, h))

NUM_LANES = len(EDGES) - 1
edges_px = [int(e * w) for e in EDGES]
history = [deque(maxlen=SMOOTH) for _ in range(NUM_LANES)]
frame_no = 0

while frame_no < MAX_FRAMES:
    ok, frame = cap.read()
    if not ok:
        break

    results = model(frame, classes=[0], verbose=False)[0]
    counts = [0] * NUM_LANES
    for box in results.boxes:
        x1, y1, x2, y2 = map(int, box.xyxy[0])
        cx = (x1 + x2) // 2
        for k in range(NUM_LANES):
            if edges_px[k] <= cx < edges_px[k + 1]:
                counts[k] += 1

    smooth = []
    for i in range(NUM_LANES):
        history[i].append(counts[i])
        smooth.append(round(sum(history[i]) / len(history[i])))

    for i, n in enumerate(smooth):
        if n <= 2:
            color = (0, 255, 0)
        elif n <= 3:
            color = (0, 255, 255)
        else:
            color = (0, 0, 255)
        lx1, lx2 = edges_px[i], edges_px[i + 1]
        cv2.rectangle(frame, (lx1, 0), (lx2, h - 1), color, 4)
        cv2.putText(frame, f"Counter {i+1}: {n} people", (lx1 + 10, 85),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.8, color, 2)
        cv2.putText(frame, f"Wait: ~{n * MINUTES_PER_PERSON} min", (lx1 + 10, 120),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.8, color, 2)

    # bottom banner
    best = smooth.index(min(smooth)) + 1
    cv2.rectangle(frame, (0, h - 50), (w, h), (0, 0, 0), -1)
    cv2.putText(frame, f"Best counter right now: Counter {best}", (20, h - 15),
                cv2.FONT_HERSHEY_SIMPLEX, 1, (255, 255, 255), 2)

    # legend
    x0, y0 = w - 240, h - 190
    cv2.rectangle(frame, (x0, y0), (w - 10, h - 60), (40, 40, 40), -1)
    for j, (lab, col) in enumerate([("Free", (0, 255, 0)),
                                    ("Busy", (0, 255, 255)),
                                    ("Crowded", (0, 0, 255))]):
        yy = y0 + 35 + j * 35
        cv2.rectangle(frame, (x0 + 15, yy - 15), (x0 + 40, yy + 5), col, -1)
        cv2.putText(frame, lab, (x0 + 55, yy),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.7, (255, 255, 255), 2)

    # title bar with timer
    secs = int(frame_no / fps)
    cv2.rectangle(frame, (0, 0), (w, 50), (40, 40, 40), -1)
    cv2.putText(frame, TITLE, (20, 35), cv2.FONT_HERSHEY_SIMPLEX, 1, (255, 255, 255), 2)
    cv2.putText(frame, f"Time: {secs // 60:02d}:{secs % 60:02d}", (w - 220, 35),
                cv2.FONT_HERSHEY_SIMPLEX, 0.9, (255, 255, 255), 2)

    out.write(frame)
    frame_no += 1

cap.release()
out.release()

